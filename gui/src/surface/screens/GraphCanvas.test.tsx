import { afterEach, expect, it, vi } from "vitest";
import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { createRef } from "react";
import { GraphCanvas, laidOut, MINIMAP_SIZE, type GraphCanvasControl } from "./GraphCanvas";
import { MiniMap, ReactFlow } from "@xyflow/react";
import type { GraphNode } from "./Graph";
vi.mock("@xyflow/react", () => ({ ReactFlow: ({ children }: { children: unknown }) => children, MiniMap: () => null, Background: () => null, MarkerType: { ArrowClosed: "closed" }, Position: { Right: "right", Left: "left", Top: "top", Bottom: "bottom" } }));
const nodes: GraphNode[] = [{ id: "a", name: "$a", state: "ok" }, { id: "b", name: "$b", detail: "running…", state: "running" }];
const edges = [{ from: "a", to: "b" }];
let tree: ReactTestRenderer | undefined;
afterEach(() => { act(() => tree?.unmount()); vi.unstubAllGlobals(); });
it("keeps recommended positions stable across changing result text and state", () => {
  const before = laidOut(nodes, edges, "LR");
  const after = laidOut([{ ...nodes[0]!, detail: "List<Record<WideTypeName>> · 900 KB" }, { ...nodes[1]!, state: "failed" }], edges, "LR");
  for (const node of nodes) expect({ x: after.get(node.id)?.x, y: after.get(node.id)?.y }).toEqual({ x: before.get(node.id)?.x, y: before.get(node.id)?.y });
});
it("moves without changing graph semantics, preserves a filtered node and separates fit from reset", () => {
  const control = createRef<GraphCanvasControl>();
  const onSelect = vi.fn();
  vi.stubGlobal("requestAnimationFrame", (callback: () => void) => callback());
  vi.stubGlobal("cancelAnimationFrame", vi.fn());
  act(() => { tree = create(<GraphCanvas ref={control} nodes={nodes} edges={edges} direction="LR" layoutId="synthetic-drag" allNodeIds={["a", "b"]} onSelect={onSelect} />); });
  const flow = () => tree!.root.findByType(ReactFlow);
  const fitView = vi.fn();
  act(() => flow().props.onInit({ fitView }));
  act(() => flow().props.onNodesChange([{ type: "select", id: "b", selected: true }]));
  expect(onSelect).toHaveBeenCalledExactlyOnceWith("b");
  const original = flow().props.nodes[0].position;
  act(() => flow().props.onNodesChange([{ type: "position", id: "a", position: { x: 800, y: 300 }, dragging: false }]));
  expect(flow().props.nodes[0].position).toEqual({ x: 800, y: 300 });
  expect(flow().props.edges).toHaveLength(1);
  expect(flow().props.nodesConnectable).toBe(false);
  act(() => { tree!.update(<GraphCanvas ref={control} nodes={[nodes[1]!]} edges={[]} direction="LR" layoutId="synthetic-drag" allNodeIds={["a", "b"]} />); });
  act(() => { tree!.update(<GraphCanvas ref={control} nodes={[{ ...nodes[0]!, state: "stale" }, nodes[1]!]} edges={edges} direction="LR" layoutId="synthetic-drag" allNodeIds={["a", "b"]} />); });
  expect(flow().props.nodes[0].position).toEqual({ x: 800, y: 300 });
  act(() => control.current!.fit());
  expect(fitView).toHaveBeenCalledOnce();
  expect(flow().props.nodes[0].position).toEqual({ x: 800, y: 300 });
  act(() => control.current!.reset());
  expect(flow().props.nodes[0].position).toEqual(original);
  expect(fitView).toHaveBeenCalledTimes(2);
  expect(tree!.root.findByType(MiniMap).props).toMatchObject({ style: MINIMAP_SIZE, pannable: true, zoomable: true, maskStrokeWidth: 1.5 });
  expect(tree!.root.findByType(MiniMap).props.nodeClassName({ data: { state: "stale", selected: true } })).toBe("graph-mini-stale graph-mini-selected");
});
it("keeps document-scoped positions when reopening, with separate workspace/orientation scopes", () => {
  act(() => { tree = create(<GraphCanvas nodes={nodes} edges={edges} direction="LR" layoutId="synthetic-reopen-lr" />); });
  act(() => tree!.root.findByType(ReactFlow).props.onNodesChange([{ type: "position", id: "a", position: { x: 700, y: 250 } }]));
  act(() => tree!.unmount());
  act(() => { tree = create(<GraphCanvas nodes={nodes} edges={edges} direction="LR" layoutId="synthetic-reopen-lr" />); });
  expect(tree!.root.findByType(ReactFlow).props.nodes[0].position).toEqual({ x: 700, y: 250 });
  act(() => { tree!.update(<GraphCanvas key="other" nodes={nodes} edges={edges} direction="TB" layoutId="synthetic-reopen-tb" />); });
  expect(tree!.root.findByType(ReactFlow).props.nodes[0].position).not.toEqual({ x: 700, y: 250 });
});
